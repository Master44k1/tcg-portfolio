export const LANGS = { de: { name: 'Deutsch', dict: de, locale: 'de-DE' }, en: { name: 'English', dict: en, locale: 'en-GB' } };

export function defaultLang() {
  const l = (navigator.language || 'de').slice(0, 2);
  return LANGS[l] ? l : 'en';
}

export function makeT(lang) {
  const dict = (LANGS[lang] || LANGS.de).dict;
  return (key, vars) => {
    let s = dict[key] ?? de[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
    return s;
  };
}
